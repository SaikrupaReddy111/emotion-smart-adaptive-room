# Fuzzy Logic Smart Room
emotion_var = ctrl.Antecedent(np.arange(0,7,1), 'emotion')
lighting = ctrl.Consequent(np.arange(0,100,1), 'lighting')
temperature = ctrl.Consequent(np.arange(16,30,1), 'temperature')

# Define all 7 FER2013 emotions
emotion_var['angry'] = fuzz.trimf(emotion_var.universe, [0,0,0])
emotion_var['disgust'] = fuzz.trimf(emotion_var.universe, [1,1,1])
emotion_var['fear'] = fuzz.trimf(emotion_var.universe, [2,2,2])
emotion_var['happy'] = fuzz.trimf(emotion_var.universe, [3,3,3])
emotion_var['sad'] = fuzz.trimf(emotion_var.universe, [4,4,4])
emotion_var['surprise'] = fuzz.trimf(emotion_var.universe, [5,5,5])
emotion_var['neutral'] = fuzz.trimf(emotion_var.universe, [6,6,6])

# Lighting sets
lighting['dim'] = fuzz.trimf(lighting.universe, [0,25,50])
lighting['normal'] = fuzz.trimf(lighting.universe, [40,60,80])
lighting['bright'] = fuzz.trimf(lighting.universe, [70,85,100])

# Temperature sets
temperature['cool'] = fuzz.trimf(temperature.universe, [16,18,22])
temperature['normal'] = fuzz.trimf(temperature.universe, [22,24,26])
temperature['warm'] = fuzz.trimf(temperature.universe, [26,28,30])

# Rules for all emotions
rules = [
    ctrl.Rule(emotion_var['angry'], lighting['dim']),
    ctrl.Rule(emotion_var['angry'], temperature['cool']),
    ctrl.Rule(emotion_var['disgust'], lighting['dim']),
    ctrl.Rule(emotion_var['disgust'], temperature['cool']),
    ctrl.Rule(emotion_var['fear'], lighting['dim']),
    ctrl.Rule(emotion_var['fear'], temperature['cool']),
    ctrl.Rule(emotion_var['happy'], lighting['bright']),
    ctrl.Rule(emotion_var['happy'], temperature['normal']),
    ctrl.Rule(emotion_var['sad'], lighting['bright']),
    ctrl.Rule(emotion_var['sad'], temperature['warm']),
    ctrl.Rule(emotion_var['surprise'], lighting['bright']),
    ctrl.Rule(emotion_var['surprise'], temperature['normal']),
    ctrl.Rule(emotion_var['neutral'], lighting['normal']),
    ctrl.Rule(emotion_var['neutral'], temperature['normal'])
]

system = ctrl.ControlSystem(rules)
sim = ctrl.ControlSystemSimulation(system)
sim.input['emotion'] = emotion_index
sim.compute()

print("\n SMART ROOM SETTINGS")
print("Lighting Level:", round(sim.output['lighting'],2))
print("Temperature Setting:", round(sim.output['temperature'],2))

