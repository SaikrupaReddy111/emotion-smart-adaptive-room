from tensorflow.keras.preprocessing.image import ImageDataGenerator
from google.colab import files
import skfuzzy as fuzz
from skfuzzy import control as ctrl
# Load dataset (train/test folders)
def load_images(path):
    X = []
    y = []
    classes = [cls for cls in os.listdir(path) if os.path.isdir(os.path.join(path, cls))]
    class_map = {cls:i for i, cls in enumerate(classes)}

    for cls in classes:
        cls_folder = os.path.join(path, cls)
        images = os.listdir(cls_folder)
        for img_name in images:
            img_path = os.path.join(cls_folder, img_name)
            img = cv2.imread(img_path, cv2.IMREAD_GRAYSCALE)
            if img is not None:
                img = cv2.resize(img, (48,48))
                X.append(img)
                y.append(class_map[cls])
    return np.array(X), np.array(y), class_map

# Load full dataset
X_train, y_train, class_map = load_images('train')
X_test, y_test, _ = load_images('test')

X_train = X_train.reshape(-1,48,48,1)/255.0
X_test = X_test.reshape(-1,48,48,1)/255.0

y_train = to_categorical(y_train, num_classes=len(class_map))
y_test = to_categorical(y_test, num_classes=len(class_map))

print("Dataset loaded")
print("X_train:", X_train.shape, "X_test:", X_test.shape)
print("Class map:", class_map)

# CNN Model
model = Sequential([
    Conv2D(32,(3,3),activation='relu',input_shape=(48,48,1)),
    MaxPooling2D(2,2),
    Conv2D(64,(3,3),activation='relu'),
    MaxPooling2D(2,2),
    Flatten(),
    Dense(128,activation='relu'),
    Dropout(0.5),
    Dense(len(class_map),activation='softmax')
])

model.compile(optimizer='adam', loss='categorical_crossentropy', metrics=['accuracy'])

# Data Augmentation + Training
datagen = ImageDataGenerator(
    rotation_range=10,
    zoom_range=0.1,
    width_shift_range=0.1,
    height_shift_range=0.1,
    horizontal_flip=True
)

model.fit(datagen.flow(X_train, y_train, batch_size=32),
          validation_data=(X_test, y_test),
          epochs=20)

model.save("emotion_model.h5")

loss, acc = model.evaluate(X_test, y_test)
print("Model Accuracy:", round(acc*100,2), "%")

