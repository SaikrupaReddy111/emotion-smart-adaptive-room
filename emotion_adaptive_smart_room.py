def suggest_music(emotion):
    if emotion=="Happy": return "Energetic music "
    elif emotion=="Sad": return "Relaxing music "
    elif emotion=="Angry": return "Calm instrumental "
    elif emotion=="Fear": return "Soft ambient "
    elif emotion=="Disgust": return "Neutral ambient "
    elif emotion=="Surprise": return "Upbeat music "
    else: return "Ambient sounds "

print("Music Suggestion:", suggest_music(emotion))

